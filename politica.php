        <section>
            <h2>4. Base Legal para o Tratamento</h2>
            <p>O tratamento dos dados pessoais pela CoopAgro será realizado com base nas seguintes hipóteses legais previstas na LGPD:</p>
            <ul>
                <li><strong>Consentimento do titular</strong> (art. 7º, I);</li>
                <li><strong>Execução de contrato ou de procedimentos preliminares relacionados a contrato</strong> do qual seja parte o titular (art. 7º, V);</li>
                <li><strong>Cumprimento de obrigação legal ou regulatória</strong> (art. 7º, II);</li>
                <li><strong>Legítimo interesse da cooperativa</strong> (art. 7º, IX), sempre respeitando os direitos e liberdades fundamentais do titular.</li>
            </ul>
        </section>

        <div class="section-divider"></div>

        <section>
            <h2>5. Compartilhamento de Dados</h2>
            <p>A CoopAgro <strong>não comercializa</strong> dados pessoais. O compartilhamento poderá ocorrer apenas nos seguintes casos:</p>
            <ul>
                <li>Com órgãos governamentais, fiscais ou regulatórios, quando exigido por lei;</li>
                <li>Com prestadores de serviços contratados pela CoopAgro, exclusivamente para atender às finalidades descritas neste documento, sempre sob cláusulas contratuais de confidencialidade e segurança;</li>
                <li>Para proteção dos interesses legítimos da cooperativa em processos judiciais, administrativos ou arbitrais.</li>
            </ul>
        </section>

        <div class="section-divider"></div>

        <section>
            <h2>6. Armazenamento e Segurança</h2>
            <p>A CoopAgro adota medidas técnicas e organizacionais aptas a proteger os dados pessoais contra acessos não autorizados, perda, alteração ou qualquer forma de tratamento inadequado ou ilícito, incluindo, mas não se limitando a:</p>
            <ul>
                <li>Controle de acesso restrito a colaboradores autorizados;</li>
                <li>Utilização de criptografia e ferramentas de segurança da informação;</li>
                <li>Aplicacao dos pilares de confidencialidade, integridade e disponibilidade</li>
                <li>Todos os dados armazenados no site possuem rotina de backup regular com redundancia e criptografia seguindo em conformidade com a ISO 27002</li>
                <li>Monitoramento e auditoria periódica dos sistemas utilizados.</li>
            </ul>
            <p>Os dados serão armazenados pelo período necessário para cumprimento das finalidades legais, regulatórias e contratuais, ou até que o titular solicite a eliminação, salvo hipóteses em que a manutenção seja exigida por lei.</p>
        </section>

        <div class="section-divider"></div>

        <section>
            <h2>7. Direitos dos Titulares</h2>
            <p>Nos termos da LGPD, o titular dos dados pessoais poderá, a qualquer tempo, solicitar à CoopAgro:</p>
            <ul>
                <li>Confirmação da existência de tratamento;</li>
                <li>Acesso aos seus dados pessoais;</li>
                <li>Correção de dados incompletos, inexatos ou desatualizados;</li>
                <li>Anonimização, bloqueio ou eliminação de dados desnecessários ou excessivos;</li>
                <li>Portabilidade dos dados a outro fornecedor de serviço;</li>
                <li>Revogação do consentimento previamente fornecido;</li>
                <li>Eliminação dos dados pessoais tratados com base no consentimento, exceto nas hipóteses de guarda legal.</li>
            </ul>
            <p>As solicitações deverão ser encaminhadas ao <strong>Encarregado de Proteção de Dados (DPO)</strong> da CoopAgro, através dos canais de contato indicados neste documento.</p>
        </section>

